#!/usr/bin/env ruby
# frozen_string_literal: true

# Generate packages/unicode_normalize/unicode_normalize/tables.rb from the
# tables.rb of the CRuby that runs this script (lib/unicode_normalize/,
# itself generated from the Unicode data by CRuby's
# template/unicode_norm_gen.tmpl).
#
# Not CRuby's file as it is: its tables are Hash literals of thousands of
# entries, which Spinel analyzes and compiles entry by entry (over a minute
# and megabytes of binary for a program that only calls unicode_normalize).
# Here each table is one String literal, entries joined by separators no
# table holds, and the Hash is built from it as the package loads. The
# regexp sources stay the Strings CRuby's are.
#
#   ruby tools/gen_unicode_normalize_tables.rb           # regenerate
#   ruby tools/gen_unicode_normalize_tables.rb --check   # fail when stale

require "unicode_normalize/tables"

OUTPUT = File.expand_path("../packages/unicode_normalize/unicode_normalize/tables.rb", __dir__)
KEY = "\u0001"
ENTRY = "\u0002"

def packed(hash)
  hash.each { |k, v| raise "a separator in the table" if "#{k}#{v}".include?(KEY) || "#{k}#{v}".include?(ENTRY) }
  hash.map { |k, v| "#{k}#{KEY}#{v}" }.join(ENTRY)
end

def literal(string)
  # Not inspect alone: a long line of escapes is one literal either way, cut for reading.
  string.scan(/.{1,200}/m).map(&:inspect).join(" \\\n    ")
end

UN = UnicodeNormalize
text = <<~RUBY
  # Generated by tools/gen_unicode_normalize_tables.rb from CRuby #{RUBY_VERSION}'s
  # lib/unicode_normalize/tables.rb (Unicode #{Encoding::UNICODE_VERSION}). Do not edit.

  module UnicodeNormalize # :nodoc:
    ACCENTS = #{literal(UN::ACCENTS)}
    REGEXP_D_STRING = #{literal(UN::REGEXP_D_STRING)}
    REGEXP_C_STRING = #{literal(UN::REGEXP_C_STRING)}
    REGEXP_K_STRING = #{literal(UN::REGEXP_K_STRING)}

    def self.unpack_table(data)
      table = {}
      data.split(#{ENTRY.inspect}).each do |entry|
        key, value = entry.split(#{KEY.inspect}, 2)
        table[key] = value
      end
      table
    end

    def self.unpack_classes(data)
      table = Hash.new(0)
      data.split(#{ENTRY.inspect}).each do |entry|
        key, value = entry.split(#{KEY.inspect}, 2)
        table[key] = value.to_i
      end
      table
    end

    CLASS_TABLE = unpack_classes(#{literal(packed(UN::CLASS_TABLE))}).freeze
    DECOMPOSITION_TABLE = unpack_table(#{literal(packed(UN::DECOMPOSITION_TABLE))}).freeze
    KOMPATIBLE_TABLE = unpack_table(#{literal(packed(UN::KOMPATIBLE_TABLE))}).freeze
    COMPOSITION_TABLE = unpack_table(#{literal(packed(UN::COMPOSITION_TABLE))}).freeze
  end
RUBY

if ARGV.include?("--check")
  abort "#{OUTPUT} is stale: run ruby tools/gen_unicode_normalize_tables.rb" unless File.exist?(OUTPUT) && File.read(OUTPUT) == text
else
  File.write(OUTPUT, text)
  puts "wrote #{OUTPUT}"
end
