# Generates lib/sp_unicase_map.inc: Unicode case mapping for String#upcase,
# #downcase, #swapcase, #capitalize and case folding (casecmp?, downcase(:fold)),
# taken from the CRuby that runs this script, so the runtime answers what
# CRuby does.
#
#   ruby tools/gen_unicase_map.rb > lib/sp_unicase_map.inc
#
# A one-codepoint mapping goes into a range table: a run of codepoints that
# all map by the same delta, either every codepoint of the run (step 1) or
# every other one (step 2, the alternating upper/lower pairs). A mapping to
# more than one codepoint ("ß".upcase is "SS") goes into a special table.
# The tables are static const data that only the case functions read, so a
# program that calls none of them links none of it (--gc-sections /
# -dead_strip).

def chars
  (0..0x10FFFF).each do |cp|
    next if cp >= 0xD800 && cp <= 0xDFFF
    yield cp, [cp].pack("U")
  end
end

maps = { upper: {}, lower: {}, fold: {}, title: {} }
special = { upper: {}, lower: {}, fold: {}, title: {}, swap: {} }
chars do |cp, s|
  u = s.upcase
  { upper: u, lower: s.downcase, fold: s.downcase(:fold) }.each do |k, r|
    next if r == s
    cps = r.unpack("U*")
    if cps.size == 1 then maps[k][cp] = cps[0]
    else special[k][cp] = cps
    end
  end
  # titlecase: where it is not the uppercase mapping (itself, for "ǅ" or
  # Georgian, whose uppercase is another letter)
  t = s.capitalize
  if t != u
    cps = t.unpack("U*")
    if cps.size == 1 then maps[:title][cp] = cps[0]
    else special[:title][cp] = cps
    end
  end
  # swapcase where it is not the uppercase mapping, or else the lowercase
  # one ("ǅ" swaps to "dž" as two codepoints)
  rule = u != s ? u : s.downcase
  w = s.swapcase
  special[:swap][cp] = w.unpack("U*") if w != rule
end

def ranges(map)
  out = []
  keys = map.keys.sort
  i = 0
  while i < keys.size
    lo = keys[i]
    d = map[lo] - lo
    # the longer of a step-1 run and a step-2 run starting here
    j1 = i
    j1 += 1 while j1 + 1 < keys.size && keys[j1 + 1] == keys[j1] + 1 && map[keys[j1 + 1]] - keys[j1 + 1] == d
    n1 = j1 - i + 1
    n2 = 1
    nxt = lo + 2
    # (a codepoint between two of the run that maps itself ends it: the
    # ranges must not overlap, the lookup is a binary search)
    n2 += 1 while map.key?(nxt + 2 * (n2 - 1)) && map[nxt + 2 * (n2 - 1)] - (nxt + 2 * (n2 - 1)) == d &&
                  !map.key?(nxt + 2 * (n2 - 1) - 1)
    if n2 > n1
      hi = lo + 2 * (n2 - 1)
      out << [lo, hi, d, 2]
      cps = (0...n2).map { |k| lo + 2 * k }
      keys -= cps[1..]
      i += 1
    else
      out << [lo, keys[j1], d, 1]
      i = j1 + 1
    end
  end
  out
end

puts "/* Generated by tools/gen_unicase_map.rb from #{RUBY_DESCRIPTION}, Unicode #{RbConfig::CONFIG["UNICODE_VERSION"]}. Do not edit. */"
%i[upper lower fold title swap].each do |k|
  rs = ranges(maps[k] || {})
  unless rs.empty?
    puts "static const sp_uc_range sp_uc_#{k}_ranges[#{rs.size}] = {"
    rs.each_slice(4) { |sl| puts "  " + sl.map { |lo, hi, d, st| "{0x#{lo.to_s(16)},0x#{hi.to_s(16)},#{d},#{st}}" }.join(",") + "," }
    puts "};"
  end
  sp = special[k].sort
  puts "static const sp_uc_special sp_uc_#{k}_special[#{[sp.size, 1].max}] = {"
  if sp.empty?
    puts "  {0,{0,0,0}},"
  else
    sp.each_slice(3) { |sl| puts "  " + sl.map { |cp, v| "{0x#{cp.to_s(16)},{#{(v + [0, 0, 0])[0, 3].map { |x| "0x#{x.to_s(16)}" }.join(",")}}}" }.join(",") + "," }
  end
  puts "};"
  puts "#define SP_UC_#{k.upcase}_NR #{rs.size}"
  puts "#define SP_UC_#{k.upcase}_NS #{sp.size}"
end
