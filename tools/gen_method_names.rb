# Regenerates the method-name tables under src/ from the running CRuby:
#
#   ruby --disable-gems tools/gen_method_names.rb
#
#   src/core_method_names.inc           every public instance method name of a
#                                       core class or module (sorted: the
#                                       compiler binary-searches it)
#   src/object_method_names.inc         Object's instance methods, public and
#                                       private (Kernel's puts, raise, ...),
#                                       as the oracle sees them
#   src/object_public_method_names.inc  Object's public instance methods, as
#                                       the oracle sees them
#   src/core_class_methods.inc          each core class's or module's own
#                                       instance methods with their
#                                       visibility, and its ancestors
#                                       (method_defined? on a builtin class)
#
# The core lists come from this run, without rubygems, so that its modules
# are not counted as core. Object's lists come from the oracle, `ruby
# --enable-frozen-string-literal`, which loads rubygems: a program sees
# Kernel's gem and gem_original_require. The helpers below are lambdas, so
# that no method of this script lands on Object.
abort "gen_method_names: run it under --disable-gems (rubygems' modules would count as core)" if defined?(Gem)
core = ObjectSpace.each_object(Module).select do |m|
  n = m.name
  n && !n.include?("::") && Object.const_get(n).equal?(m) rescue false
end
names = core.flat_map(&:public_instance_methods).map(&:to_s).uniq.sort
require "rbconfig"   # (after the core list, which must not count it)
oracle = lambda do |expr|
  IO.popen([RbConfig.ruby, "--enable-frozen-string-literal", "-e", "puts(#{expr})"], &:read).split("\n")
end
obj_all = oracle.("(Object.instance_methods + Object.private_instance_methods).map(&:to_s).uniq.sort")
obj_pub = oracle.("Object.public_instance_methods.map(&:to_s).uniq.sort")
abort "gen_method_names: the oracle listed no Object methods" if obj_all.empty? || obj_pub.empty?

emit = lambda do |path, header, list|
  File.write(path, "/* Generated by tools/gen_method_names.rb from CRuby #{RUBY_VERSION}: do not edit.\n" \
                   "   #{header} */\n" +
                   list.map { |n| "  #{n.dump},\n" }.join)
end
dir = File.expand_path("../src", __dir__)
emit.("#{dir}/core_method_names.inc",
      "Every public instance method name of a core class or module, sorted.", names)
emit.("#{dir}/object_method_names.inc",
      "Object's instance method names, public and private.", obj_all)
emit.("#{dir}/object_public_method_names.inc", "Object's public instance method names.", obj_pub)

# A row per own instance method (CCM: class, name, 1 public / 2 protected /
# 4 private) and one per class with its ancestors (CCA), for every core module
# and every module among their ancestors (Random::Formatter, ...).
mods = (core + core.flat_map(&:ancestors)).uniq.sort_by(&:to_s)
rows = mods.flat_map do |m|
  own = [[m.public_instance_methods(false), 1], [m.protected_instance_methods(false), 2],
         [m.private_instance_methods(false), 4]]
  own.flat_map { |ms, v| ms.map { |x| [x.to_s, v] } }.sort.map { |x, v| "CCM(#{m.to_s.dump}, #{x.dump}, #{v})\n" } +
    ["CCA(#{m.to_s.dump}, #{m.ancestors.map(&:to_s).join(" ").dump})\n"]
end
File.write("#{dir}/core_class_methods.inc",
           "/* Generated by tools/gen_method_names.rb from CRuby #{RUBY_VERSION}: do not edit.\n" \
           "   Each core class's or module's own instance methods with their visibility\n" \
           "   (1 public, 2 protected, 4 private), and its ancestors. */\n" + rows.join)

# A row per public method a core class or module answers as a value
# (CSM: class, name) beyond the ones every class (Class's public instance
# methods) or every module (Module's) answers: its own and inherited
# singleton methods (File.join, Exception.to_tty?, Kernel.trap).
srows = core.sort_by(&:to_s).flat_map do |m|
  (m.public_methods - (m.is_a?(Class) ? Class : Module).public_instance_methods).map(&:to_s).sort
    .map { |x| "CSM(#{m.to_s.dump}, #{x.dump})\n" }
end
# and the ones every class ("Class#") or every module ("Module#") answers
# from Class or Module itself (not Object's or Kernel's, which a program's
# own Object method replaces)
srows += [Class, Module].flat_map do |k|
  k.public_instance_methods.select { |x| [Class, Module].include?(k.instance_method(x).owner) }
   .map(&:to_s).sort.map { |x| "CSM(#{"#{k}#".dump}, #{x.dump})\n" }
end
File.write("#{dir}/core_singleton_methods.inc",
           "/* Generated by tools/gen_method_names.rb from CRuby #{RUBY_VERSION}: do not edit.\n" \
           "   Each core class's or module's public methods as a value, beyond Class's\n" \
           "   (a class) or Module's (a module) public instance methods, and those\n" \
           "   (\"Class#\", \"Module#\"). */\n" + srows.join)
